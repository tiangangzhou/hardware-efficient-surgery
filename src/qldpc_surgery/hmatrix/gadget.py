"""Surgery gadgets as mapping cones, and ``build_gadget``.

A gadget measuring X-type logicals attaches an auxiliary complex
A_1 --d1--> A_0 --d0--> A_-1 to the data code (SM, "CSS surgery as a mapping cone";
Ide, Gowda, Nadkarni, Dauphinais arXiv:2410.02753 Eqs. (12)-(13)). For a graph,
A_1 are the vertices (one new X check each), A_0 the edges (auxiliary qubits) and
A_-1 the cycles (new Z checks). The arrays stored here are

    incidence = d1   (|A_0| x |A_1|, the edge-vertex incidence matrix),
    partial_0 = d0   (|A_-1| x |A_0|),
    f1               (n x |A_1|, maps vertices to data qubits),
    f0               (rows of H_Z x |A_0|, maps edges to Z checks),

and the merged checks are

    H~_X = [[H_X, 0], [f1^T, d1^T]],    H~_Z = [[H_Z, f0], [0, d0]].

They commute iff H_Z f1 = f0 d1 and d0 d1 = 0. The product of the new X checks
selected by r in ker d1 is the data operator X(f1 r), so the measured logicals are
f1(ker d1): X(f1 1) = X(x) alone for a connected graph. A cycle c (c d1 = 0) commutes
with every check, so it must be generated by the rows of d0 and the cycles
{v^T f0 : v^T H_Z = 0} of the data checks, or it would be a new logical. A Z-type
measurement exchanges H_X and H_Z; the SM writes this Z-type form (its Eq. (S2)).

A gadget may measure t logicals at once (SM, "Parallel measurements with one
auxiliary code"): ``batch_x[j] = f1 @ readout_vectors[j]`` with
``readout_vectors[j]`` in ker d1, and the j-th outcome is the product of the new
checks selected by ``readout_vectors[j]``.
"""

from __future__ import annotations

import dataclasses
from typing import Any

import galois
import numpy as np
from qldpc.codes.common import CSSCode
from qldpc.objects import Pauli, PauliXZ

GF2 = galois.GF(2)


def bitmask(row: np.ndarray) -> int:
    """Pack a 0/1 vector into a Python int (bit i is ``row[i]``)."""
    return int.from_bytes(
        np.packbits(np.asarray(row, np.uint8), bitorder="little").tobytes(), "little"
    )


class XorBasis:
    """Incremental GF(2) row echelon basis of bit-packed rows (pivot = highest bit)."""

    def __init__(self) -> None:
        self.pivots: dict[int, int] = {}

    def __len__(self) -> int:
        return len(self.pivots)

    def reduce(self, mask: int) -> int:
        while mask and (top := mask.bit_length() - 1) in self.pivots:
            mask ^= self.pivots[top]
        return mask

    def add(self, mask: int) -> bool:
        """Add a row; return whether it was independent of the rows added so far."""
        mask = self.reduce(mask)
        if mask:
            self.pivots[mask.bit_length() - 1] = mask
        return bool(mask)


def gf2_rank(matrix: np.ndarray) -> int:
    basis = XorBasis()
    for row in np.asarray(matrix, np.uint8):
        basis.add(bitmask(row))
    return len(basis)


def basis_matrices(code: CSSCode, basis: PauliXZ) -> tuple[np.ndarray, np.ndarray]:
    """(H_meas, H_comp): (H_X, H_Z) for an X-type measurement, swapped for Z."""
    hx = np.asarray(code.matrix_x, np.uint8)
    hz = np.asarray(code.matrix_z, np.uint8)
    return (hx, hz) if basis is Pauli.X else (hz, hx)


def complementary_checks(code: CSSCode, x: np.ndarray, basis: PauliXZ) -> np.ndarray:
    """H_comp, after checking that ``x`` is the support of a ``basis``-type logical."""
    H = basis_matrices(code, basis)[1]
    if (H @ np.asarray(x, np.uint8) % 2).any():
        raise ValueError(f"x does not commute with the complementary checks of a {basis} logical")
    return H


def assemble_mapping_cone(
    H_meas: np.ndarray,
    H_comp: np.ndarray,
    f1: np.ndarray,
    incidence: np.ndarray,
    f0: np.ndarray,
    partial_0: np.ndarray,
) -> tuple[np.ndarray, np.ndarray]:
    """Merged checks [[H_meas, 0], [f1^T, d1^T]] and [[H_comp, f0], [0, d0]]."""
    zeros = np.zeros
    M_meas = np.block(
        [[H_meas, zeros((len(H_meas), len(incidence)), np.uint8)], [f1.T, incidence.T]]
    )
    M_comp = np.block(
        [[H_comp, f0], [zeros((len(partial_0), H_meas.shape[1]), np.uint8), partial_0]]
    )
    return M_meas.astype(np.uint8), M_comp.astype(np.uint8)


@dataclasses.dataclass(frozen=True, eq=False)
class GadgetSpec:
    """The four maps of one gadget on ``code``; see the module docstring.

    ``x`` is the measured operator (for a batch, ``batch_x[0]``). ``batch_x`` and
    ``readout_vectors`` default to ``x`` and the all-ones vector over the new checks.
    The merged matrices are derived from the maps on every access.
    """

    code: CSSCode
    x: np.ndarray
    basis: PauliXZ
    f1: np.ndarray
    incidence: np.ndarray
    f0: np.ndarray
    partial_0: np.ndarray
    batch_x: np.ndarray | None = None
    readout_vectors: np.ndarray | None = None

    @property
    def effective_batch_x(self) -> np.ndarray:
        return self.x.reshape(1, -1) if self.batch_x is None else self.batch_x

    @property
    def effective_readout_vectors(self) -> np.ndarray:
        if self.readout_vectors is None:
            return np.ones((1, self.f1.shape[1]), dtype=np.uint8)
        return self.readout_vectors

    def _merged(self) -> tuple[np.ndarray, np.ndarray]:
        H_meas, H_comp = basis_matrices(self.code, self.basis)
        m, c = assemble_mapping_cone(
            H_meas, H_comp, self.f1, self.incidence, self.f0, self.partial_0
        )
        return (m, c) if self.basis is Pauli.X else (c, m)

    @property
    def HX_merged(self) -> np.ndarray:
        return self._merged()[0]

    @property
    def HZ_merged(self) -> np.ndarray:
        return self._merged()[1]

    def validate(self) -> None:
        """Check that the merged checks commute and that every readout vector r
        lies in ker d1 with f1 r equal to its row of ``batch_x``."""
        hx, hz = GF2(self.HX_merged), GF2(self.HZ_merged)
        if (hx @ hz.T).any():
            raise ValueError("merged checks do not commute: H_Z f1 != f0 d1 or d0 d1 != 0")
        readout = self.effective_readout_vectors
        if (self.incidence.astype(int) @ readout.T % 2).any():
            raise ValueError("a readout vector is not in ker d1")
        if not np.array_equal(readout @ self.f1.T.astype(int) % 2, self.effective_batch_x):
            raise ValueError("f1 @ readout_vectors[j] differs from batch_x[j]")

    @classmethod
    def from_maps(
        cls,
        code: CSSCode,
        x: np.ndarray,
        *,
        basis: PauliXZ,
        f1: np.ndarray,
        incidence: np.ndarray,
        f0: np.ndarray,
        partial_0: np.ndarray,
        batch_x: np.ndarray | None = None,
        readout_vectors: np.ndarray | None = None,
        validate: bool = True,
    ) -> GadgetSpec:
        """Gadget from user-supplied maps (all 0/1 arrays), validated by default."""

        def u8(a: np.ndarray | None) -> np.ndarray | None:
            return None if a is None else np.asarray(a).astype(np.uint8)

        spec = cls(
            code,
            u8(x),
            basis,
            u8(f1),
            u8(incidence),
            u8(f0),
            u8(partial_0),
            u8(batch_x),
            u8(readout_vectors),
        )
        if validate:
            spec.validate()
        return spec


def build_gadget(
    code: CSSCode,
    x: np.ndarray,
    *,
    basis: PauliXZ,
    method: str = "edge_expansion",
    validate: bool = False,
    **kw: Any,
) -> GadgetSpec:
    """Gadget measuring the ``basis``-type logical supported on ``x``.

    ``method="edge_expansion"`` is Graph-IGND (arXiv:2410.02753 Algorithm 3,
    ``edge_expansion.edge_expansion_maps``); ``method="gauging"`` is Graph-WY
    (arXiv:2410.02213, ``gauging.gauging_maps``). ``kw`` goes to that function.
    """
    from .edge_expansion import edge_expansion_maps  # these modules import this one
    from .gauging import gauging_maps

    producers = {"edge_expansion": edge_expansion_maps, "gauging": gauging_maps}
    if method not in producers:
        raise ValueError(f"unknown construction {method!r}; available: {sorted(producers)}")
    f1, incidence, f0, partial_0 = producers[method](code, x, basis=basis, **kw)
    return GadgetSpec.from_maps(
        code,
        x,
        basis=basis,
        f1=f1,
        incidence=incidence,
        f0=f0,
        partial_0=partial_0,
        validate=validate,
    )
