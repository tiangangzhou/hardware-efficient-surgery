"""Edge-expanded homological measurement ("Graph-IGND").

Ide, Gowda, Nadkarni, Dauphinais, "Fault-tolerant logical measurements via
homological measurement", arXiv:2410.02753, Sec. III B, Algorithms 1-3. Notation as
in ``gadget.py``: ``incidence`` is d1 (edges x vertices, vertices = supp(x)),
``partial_0`` is d0, and H is the check matrix complementary to the measured Pauli
type (H_Z for X, H_X for Z).

Algorithm 3 restricts H to supp(x) (Eqs. (35), (47), (48)), raises the Cheeger
constant of this hypergraph to 1 with Algorithm 1 (which preserves the distance,
Sec. III B), and picks a sparse d0 that complements the cycles already generated by
the data checks (Algorithm 2). If d0 is too heavy, it restarts from the restricted
hypergraph, splits hyperedges into weight-two edges, and cellulates long cycles.
Deterministic choices replace the paper's open ones:

- Cheeger constants are exact: all cuts are enumerated for |V| <= 20, and above an
  integer program (HiGHS) finds the sparsest cut. Above 20 vertices Algorithm 1 works
  with the Fiedler sweep cuts and the violated cuts found so far, and stops only when
  the integer program finds no cut with |dS| < |S|, so h >= 1 always holds exactly;
- Algorithm 2's random search is replaced by a greedy minimum-weight basis drawn
  from Horton's candidate cycles (J. D. Horton, SIAM J. Comput. 16, 358 (1987));
- a hyperedge is split by a matching that first joins different components;
- a long simple cycle is cut by a chord between opposite vertices.
"""

from __future__ import annotations

import collections
import itertools
import math
from fractions import Fraction

import networkx as nx
import numpy as np
from qldpc.codes.common import CSSCode
from qldpc.objects import PauliXZ
from scipy.optimize import Bounds, LinearConstraint, milp

from .gadget import GF2, XorBasis, bitmask, complementary_checks

_EXACT_CHEEGER_MAX_V = 20  # all 2^|V| cuts are enumerated up to this size, above an ILP


def restrict_maps(H: np.ndarray, x: np.ndarray) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    """(f1, d1*, f0*) of Eqs. (35), (47), (48): d1* is H restricted to supp(x) with
    its zero rows removed, f0* maps each edge to its check, f1 each vertex to its qubit."""
    support = np.flatnonzero(x)
    H_Q = np.asarray(H, np.uint8)[:, support]
    rows = np.flatnonzero(H_Q.any(axis=1))
    f1 = np.zeros((len(x), len(support)), np.uint8)
    f1[support, np.arange(len(support))] = 1
    f0 = np.zeros((len(H_Q), len(rows)), np.uint8)
    f0[rows, np.arange(len(rows))] = 1
    return f1, H_Q[rows], f0


def _cut_sizes(incidence: np.ndarray, cuts: np.ndarray) -> np.ndarray:
    """|dS| for every cut S (rows of ``cuts``): the edges meeting S an odd number of times."""
    return (incidence @ cuts.T % 2).sum(axis=0)


def _all_cuts(n_v: int) -> np.ndarray:
    """Indicator rows of all vertex sets S with 1 <= |S| <= n_v/2."""
    masks = np.arange(1, 1 << n_v, dtype=np.uint32)
    cuts = np.empty((len(masks), n_v), np.uint8)
    for v in range(n_v):
        cuts[:, v] = (masks >> v) & 1
    return cuts[cuts.sum(axis=1) <= n_v // 2]


def _fiedler_sweep_cuts(incidence: np.ndarray) -> np.ndarray:
    """Prefix and suffix sets (1 <= |S| <= |V|/2) of the vertices sorted by the Fiedler
    vector of the graph Laplacian, with every hyperedge expanded into a clique. Sweeping
    from both ends makes the cuts independent of the sign LAPACK gives the vector."""
    adjacency = incidence.T.astype(np.float64) @ incidence
    np.fill_diagonal(adjacency, 0)
    laplacian = np.diag(adjacency.sum(axis=1)) - adjacency
    order = np.argsort(np.linalg.eigh(laplacian)[1][:, 1], kind="stable")
    n_v = incidence.shape[1]
    half = n_v // 2
    cuts = np.zeros((2 * half, n_v), np.uint8)
    for k in range(half):
        cuts[k:half, order[k]] = 1
        cuts[half + k :, order[-1 - k]] = 1
    return cuts


def _min_cut_excess(incidence: np.ndarray, ratio: Fraction) -> tuple[Fraction, np.ndarray]:
    """min |dS| - ratio |S| over 1 <= |S| <= |V|/2 and a minimising S, by an integer
    program in s_v = [v in S], y_e = [e in dS] and k_e, with |e & S| = 2 k_e + y_e."""
    n_e, n_v = incidence.shape
    p, q = ratio.numerator, ratio.denominator
    cost = np.r_[np.full(n_v, -p), np.full(n_e, q), np.zeros(n_e)]  # q |dS| - p |S|
    parity = LinearConstraint(np.hstack([incidence, -np.eye(n_e), -2 * np.eye(n_e)]), 0, 0)
    size = LinearConstraint(np.r_[np.ones(n_v), np.zeros(2 * n_e)], 1, n_v // 2)
    upper = np.r_[np.ones(n_v + n_e), incidence.sum(axis=1) // 2]
    result = milp(
        cost,
        constraints=[parity, size],
        integrality=np.ones(len(cost)),
        bounds=Bounds(0, upper),
        options={"mip_rel_gap": 0},
    )
    if not result.success:
        raise RuntimeError(f"Cheeger integer program failed: {result.message}")
    S = np.round(result.x[:n_v]).astype(np.uint8)
    return int(_cut_sizes(incidence, S[None])[0]) - ratio * int(S.sum()), S


def sparsest_cut(incidence: np.ndarray) -> tuple[float, np.ndarray]:
    """(h, S): the Cheeger constant h = min_{1 <= |S| <= |V|/2} |dS|/|S| (Eq. (3)) and a
    minimising S, both exact: the first S of a Gray-code enumeration for |V| <= 20, above
    Dinkelbach's iteration of the integer program from the best Fiedler sweep cut."""
    inc = np.asarray(incidence, np.uint8)
    n_v = inc.shape[1]
    if n_v < 2:
        return math.inf, np.zeros(n_v, np.uint8)
    if n_v > _EXACT_CHEEGER_MAX_V:
        cuts = _fiedler_sweep_cuts(inc)
        counts, sizes = _cut_sizes(inc, cuts), cuts.sum(axis=1)
        best = int(np.argmin(counts / sizes))
        h, S = Fraction(int(counts[best]), int(sizes[best])), cuts[best].copy()
        while h > 0:  # each step finds a cut of smaller ratio, until none exists
            excess, cut = _min_cut_excess(inc, h)
            if excess >= 0:
                break
            h, S = Fraction(int(_cut_sizes(inc, cut[None])[0]), int(cut.sum())), cut
        return float(h), S
    # Gray-code walk over all subsets, updating the bit-packed dS by one XOR per step.
    columns = [bitmask(column) for column in inc.T]
    best, best_mask, mask, boundary = math.inf, 0, 0, 0
    for k in range(1, 1 << n_v):
        bit = (k & -k).bit_length() - 1
        mask ^= 1 << bit
        boundary ^= columns[bit]
        size = mask.bit_count()
        if size <= n_v // 2 and boundary.bit_count() < best * size:
            best, best_mask = boundary.bit_count() / size, mask
    return best, np.array([(best_mask >> v) & 1 for v in range(n_v)], np.uint8)


def cheeger_constant(incidence: np.ndarray) -> float:
    return sparsest_cut(incidence)[0]


def algorithm_1(incidence: np.ndarray, *, max_extra: int = 200) -> np.ndarray:
    """Algorithm 1: add weight-two edges (rows) until the Cheeger constant is 1.

    Each step takes a sparsest cut S and adds, among the edges joining a minimum-degree
    vertex of S to a minimum-degree vertex outside S, the first one that maximises the
    new Cheeger constant. Up to 20 vertices this runs over all cuts. Above, it runs over
    the known cuts (the Fiedler sweep cuts of the current graph and every violated cut
    found so far); once all have |dS| >= |S|, the integer program of ``sparsest_cut``
    looks for a cut with |dS| < |S|, and the loop stops only when there is none.
    """
    E = np.array(incidence, np.uint8)
    n_v = E.shape[1]
    if n_v < 2:
        return E
    exact = n_v <= _EXACT_CHEEGER_MAX_V
    if exact:
        cuts = _all_cuts(n_v)
        counts = _cut_sizes(E, cuts)
    violated = np.zeros((0, n_v), np.uint8)
    for added in itertools.count():
        while not exact:  # the sweep cuts depend on the graph
            cuts = np.unique(np.vstack([_fiedler_sweep_cuts(E), violated]), axis=0)
            counts = _cut_sizes(E, cuts)
            if (counts < cuts.sum(axis=1)).any():
                break
            excess, cut = _min_cut_excess(E, Fraction(1))
            if excess >= 0:
                return E  # certified: no cut has |dS| < |S|
            violated = np.vstack([violated, cut])
        sizes = cuts.sum(axis=1)
        if (counts >= sizes).all():
            return E
        if added == max_extra:
            raise RuntimeError(f"Algorithm 1 exceeded max_extra={max_extra}")
        S = sparsest_cut(E)[1] if exact else cuts[np.argmin(counts / sizes)]
        degree = E.sum(axis=0)
        inside, outside = np.flatnonzero(S), np.flatnonzero(S == 0)
        h_best, best = -math.inf, None
        for v1 in inside[degree[inside] == degree[inside].min()]:
            for v2 in outside[degree[outside] == degree[outside].min()]:
                delta = cuts[:, v1] ^ cuts[:, v2]  # does the edge (v1, v2) cross S?
                h = float(((counts + delta) / sizes).min())
                if h > h_best:
                    h_best, best = h, (v1, v2, delta)
        v1, v2, delta = best
        edge = np.zeros((1, n_v), np.uint8)
        edge[0, [v1, v2]] = 1
        E = np.vstack([E, edge])
        counts = counts + delta


def _horton_candidates(incidence: np.ndarray) -> list[frozenset[int]]:
    """Fundamental cycles (edge sets) of the BFS trees rooted at every vertex, lightest
    first. This candidate set contains a minimum cycle basis (Horton); hyperedges are
    ignored."""
    n_edges, n_v = incidence.shape
    ends: dict[int, tuple[int, int]] = {}
    adjacent: dict[int, list[tuple[int, int]]] = {v: [] for v in range(n_v)}
    for e in range(n_edges):
        vs = np.flatnonzero(incidence[e])
        if len(vs) == 2:
            u, v = int(vs[0]), int(vs[1])
            ends[e] = (u, v)
            adjacent[u].append((v, e))
            adjacent[v].append((u, e))
    candidates: dict[frozenset[int], None] = {}
    for root in range(n_v):
        parent = {root: (-1, -1)}  # vertex -> (parent, tree edge)
        queue = collections.deque([root])
        while queue:
            a = queue.popleft()
            for b, e in adjacent[a]:
                if b not in parent:
                    parent[b] = (a, e)
                    queue.append(b)
        tree = {e for _, e in parent.values()}

        def to_root(a: int) -> set[int]:
            path = set()
            while parent[a][0] != -1:
                a, e = parent[a]
                path.add(e)
            return path

        for e, (u, v) in ends.items():
            if e not in tree and u in parent and v in parent:
                candidates.setdefault(frozenset({e} ^ (to_root(u) ^ to_root(v))))
    return sorted(candidates, key=len)


def algorithm_2(incidence: np.ndarray, H: np.ndarray, f0: np.ndarray) -> np.ndarray:
    """d0 of Algorithm 2: a low-weight basis of the cycle space ker d1^T modulo the
    cycles V = {v^T f0 : v^T H = 0} that the merged data checks already generate.

    Instead of the paper's random search, cycles are taken greedily, lightest first
    (a minimum-weight choice among the candidates), from Horton's candidates and then
    from a basis of the whole cycle space (which covers cycles through hyperedges),
    keeping those independent modulo V and the cycles chosen so far. Among cycles of
    equal weight, the one sharing the fewest extra edges with the f0 rows and the
    chosen cycles comes first (two rows sharing two edges form a 4-cycle in the
    Tanner graph).
    """
    n_edges = incidence.shape[0]
    f0 = np.asarray(f0, np.uint8)
    span = XorBasis()
    if len(H):
        for row in np.asarray(GF2(np.asarray(H, np.uint8)).left_null_space() @ GF2(f0)):
            span.add(bitmask(row))
    cycle_space = np.asarray(GF2(np.asarray(incidence, np.uint8)).left_null_space())
    target = len(cycle_space) - len(span)
    chosen: list[np.ndarray] = []
    context = [mask for mask in map(bitmask, f0) if mask]

    def take(pool: list[tuple[int, list[int] | np.ndarray]]) -> bool:
        """Accept independent cycles of one weight class; True once d0 is complete."""
        penalty = [sum(max(0, (m & c).bit_count() - 1) for c in context) for m, _ in pool]
        while pool:
            i = min(range(len(pool)), key=penalty.__getitem__)
            mask, edges = pool.pop(i)
            penalty.pop(i)
            if not span.add(mask):
                continue
            row = np.zeros(n_edges, np.uint8)
            row[edges] = 1
            chosen.append(row)
            context.append(mask)
            if len(chosen) == target:
                return True
            penalty = [p + max(0, (m & mask).bit_count() - 1) for p, (m, _) in zip(penalty, pool)]
        return False

    if target > 0 and not any(
        take([(sum(1 << e for e in c), list(c)) for c in group])
        for _, group in itertools.groupby(_horton_candidates(incidence), key=len)
    ):
        weight = lambda row: int(row.sum())
        for _, group in itertools.groupby(sorted(cycle_space, key=weight), key=weight):
            if take([(bitmask(row), np.flatnonzero(row)) for row in group]):
                break
    return np.array(chosen, np.uint8).reshape(-1, n_edges)


def _matching(vertices: list[int], components: nx.utils.UnionFind) -> list[tuple[int, int]]:
    """Pair up ``vertices``, joining different components first, otherwise in order."""
    unmatched, pairs = list(vertices), []
    while len(unmatched) >= 2:
        i, j = next(
            (
                (i, j)
                for i in range(len(unmatched))
                for j in range(i + 1, len(unmatched))
                if components[unmatched[i]] != components[unmatched[j]]
            ),
            (0, 1),
        )
        a, b = unmatched[i], unmatched[j]
        components.union(a, b)
        pairs.append((a, b))
        del unmatched[j], unmatched[i]
    return pairs


def expand_hyperedges(incidence: np.ndarray, f0: np.ndarray) -> tuple[np.ndarray, np.ndarray]:
    """Algorithm 3, lines 8-11: replace each hyperedge e (weight > 2) by wt(e)/2
    weight-two edges summing to e, each with a copy of e's f0 column. Matching
    different components first keeps the Cheeger constant high."""
    n_v = incidence.shape[1]
    components = nx.utils.UnionFind(range(n_v))
    for row in incidence:
        if row.sum() == 2:
            components.union(*np.flatnonzero(row).tolist())
    rows, columns = [], []
    for row, column in zip(incidence, f0.T):
        vertices = np.flatnonzero(row).tolist()
        for pair in [vertices] if len(vertices) <= 2 else _matching(vertices, components):
            new = np.zeros(n_v, np.uint8)
            new[list(pair)] = 1
            rows.append(new)
            columns.append(column)
    return np.array(rows, np.uint8), np.array(columns, np.uint8).T


def _simple_cycle(remaining: set[int], ends) -> list[int]:
    """Remove and return one simple cycle from an even-degree edge set ``remaining``."""
    adjacent: dict[int, list[int]] = {}
    for e in remaining:
        for v in ends(e):
            adjacent.setdefault(v, []).append(e)
    current = next(iter(adjacent))
    position, path = {current: 0}, []
    while True:
        e = next(e for e in adjacent[current] if e not in path)
        u, v = ends(e)
        current = v if u == current else u
        path.append(e)
        if current in position:
            cycle = path[position[current] :]
            remaining.difference_update(cycle)
            return cycle
        position[current] = len(position)


def _vertex_order(cycle: list[int], ends) -> list[int]:
    """Vertices of a simple cycle in traversal order, from its smallest vertex."""
    adjacent: dict[int, list[int]] = {}
    for e in cycle:
        u, v = ends(e)
        adjacent.setdefault(u, []).append(v)
        adjacent.setdefault(v, []).append(u)
    order, previous = [min(adjacent)], -1
    for _ in range(len(cycle) - 1):
        a, b = adjacent[order[-1]]
        order, previous = order + [b if a == previous else a], order[-1]
    return order


def cellulate(
    partial_0: np.ndarray, incidence: np.ndarray, f0: np.ndarray, *, target_weight: int
) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    """Algorithm 3, lines 15-17: split every row of d0 heavier than ``target_weight``.

    All edges must have weight two. A row that is an edge-disjoint union of several
    simple cycles is replaced by them; a simple cycle is cut by a new edge (chord)
    between opposite vertices, with a zero f0 column, into two cycles through the chord.
    Every step lowers sum(max(0, wt - target_weight)) when ``target_weight`` >= 3.
    Returns (d0, d1, f0).
    """
    if target_weight < 3:
        raise ValueError("cycles cannot be cellulated below weight 3")
    rows = [set(int(e) for e in np.flatnonzero(row)) for row in partial_0]

    def ends(e: int) -> tuple[int, int]:
        u, v = np.flatnonzero(incidence[e])
        return int(u), int(v)

    while (
        idx := next((i for i, r in enumerate(rows) if len(r) > target_weight), None)
    ) is not None:
        remaining, pieces = set(rows[idx]), []
        while remaining:
            pieces.append(_simple_cycle(remaining, ends))
        if len(pieces) > 1:
            rows[idx] = set(pieces[0])
            rows.extend(set(piece) for piece in pieces[1:])
            continue
        order = _vertex_order(pieces[0], ends)
        k, chord = len(order), len(incidence)
        edge_of = {frozenset(ends(e)): e for e in pieces[0]}
        new = np.zeros((1, incidence.shape[1]), np.uint8)
        new[0, [order[0], order[k // 2]]] = 1
        incidence = np.vstack([incidence, new])
        f0 = np.hstack([f0, np.zeros((len(f0), 1), np.uint8)])
        arc = lambda a, b: {edge_of[frozenset((order[i], order[(i + 1) % k]))] for i in range(a, b)}
        arc_1, arc_2 = arc(0, k // 2), arc(k // 2, k)
        rows[idx] = {e for e in arc_1} | {chord}
        rows.append({e for e in arc_2} | {chord})
    d0 = np.zeros((len(rows), len(incidence)), np.uint8)
    for i, row in enumerate(rows):
        d0[i, list(row)] = 1
    return d0, incidence, f0


def algorithm_3(
    H: np.ndarray, x: np.ndarray, *, cellulate_to: int | None = None
) -> tuple[np.ndarray, np.ndarray, np.ndarray, np.ndarray]:
    """Algorithm 3 for the logical supported on ``x``; returns (f1, d1, f0, d0).

    The branch (lines 5-18) runs when d0 has a row heavier than ``cellulate_to``
    (never if it is None) and cellulates down to that weight.
    """
    f1, incidence_star, f0_star = restrict_maps(H, x)  # line 1
    incidence = algorithm_1(incidence_star)  # line 2
    f0 = _pad_columns(f0_star, len(incidence))  # line 3
    partial_0 = algorithm_2(incidence, H, f0)  # line 4
    if cellulate_to is not None and partial_0.sum(axis=1).max(initial=0) > cellulate_to:
        incidence, f0 = expand_hyperedges(incidence_star, f0_star)  # lines 6-11
        incidence = algorithm_1(incidence)  # line 12
        f0 = _pad_columns(f0, len(incidence))  # line 13
        partial_0 = algorithm_2(incidence, H, f0)  # line 14
        partial_0, incidence, f0 = cellulate(  # lines 15-17
            partial_0, incidence, f0, target_weight=cellulate_to
        )
    return f1, incidence, f0, partial_0


def _pad_columns(f0: np.ndarray, n_edges: int) -> np.ndarray:
    """Zero f0 columns for the edges added by Algorithm 1 (lines 3 and 13)."""
    return np.hstack([f0, np.zeros((len(f0), n_edges - f0.shape[1]), np.uint8)])


def edge_expansion_maps(
    code: CSSCode,
    x: np.ndarray,
    *,
    basis: PauliXZ,
    cellulate_to: int | str | None = "native",
) -> tuple[np.ndarray, np.ndarray, np.ndarray, np.ndarray]:
    """(f1, d1, f0, d0) of Graph-IGND for the ``basis``-type logical on ``x``.

    ``cellulate_to="native"`` uses the largest complementary check weight.
    """
    H = complementary_checks(code, x, basis)
    if cellulate_to == "native":
        cellulate_to = int(H.sum(axis=1).max())
    return algorithm_3(H, np.asarray(x, np.uint8), cellulate_to=cellulate_to)
